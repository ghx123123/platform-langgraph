# ----------------------------------------------------------------- 基础工具
def set_font(run, name=SONG, size=12, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)
    rFonts.set(qn("w:eastAsia"), name)


def para(doc, text="", *, font=SONG, size=12, bold=False, align=None,
         indent_chars=2, line=1.5, space_before=0, space_after=6):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    if align is not None:
        p.alignment = align
    if line:
        pf.line_spacing = line
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    if indent_chars:
        # 首行缩进 N 字符（东亚版式）
        pPr = p._element.get_or_add_pPr()
        ind = pPr.find(qn("w:ind"))
        if ind is None:
            ind = OxmlElement("w:ind")
            pPr.append(ind)
        ind.set(qn("w:firstLineChars"), str(int(indent_chars * 100)))
        ind.set(qn("w:firstLine"), str(int(size * 20 * indent_chars)))
    if text:
        set_font(p.add_run(text), font, size, bold)
    return p


def h1(doc, text, page_break_before=True):
    p = para(doc, text, font=HEI, size=16, bold=False, indent_chars=0,
             line=1.5, space_before=14, space_after=8)
    if page_break_before:
        # 用「段前分页」而不是章末插入分页符：章末分页符在内容正好落满一页时
        # 会多出一整页空白（实测出现仅 2 个字符的空白页）。
        p.paragraph_format.page_break_before = True
    return p


def h2(doc, text):
    return para(doc, text, font=HEI, size=14, indent_chars=0,
                line=1.5, space_before=10, space_after=6)


def h3(doc, text):
    return para(doc, text, font=HEI, size=12, indent_chars=0,
                line=1.5, space_before=8, space_after=4)


def bullet(doc, text, size=12):
    """项目符号段落，悬挂缩进。"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(3)
    pf.left_indent = Cm(0.74)
    pf.first_line_indent = Cm(-0.37)
    set_font(p.add_run("· " + text), SONG, size)
    return p


def figure(doc, filename, caption, width=CONTENT_W):
    """插入截图 + 图题。"""
    path = IMG / filename
    if not path.exists():
        para(doc, f"[缺少截图：{filename}]", align=WD_ALIGN_PARAGRAPH.CENTER, indent_chars=0)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(str(path), width=width)
    cap = para(doc, caption, size=10.5, align=WD_ALIGN_PARAGRAPH.CENTER,
               indent_chars=0, line=1.2, space_after=10)
    return cap


def table(doc, headers, rows, widths=None, caption=None):
    if caption:
        para(doc, caption, size=10.5, align=WD_ALIGN_PARAGRAPH.CENTER,
             indent_chars=0, line=1.2, space_after=4)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.line_spacing = 1.2
        set_font(p.add_run(htext), HEI, 10.5)
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.line_spacing = 1.2
            if i == 0 or len(str(value)) < 14:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            set_font(p.add_run(str(value)), SONG, 10.5)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = w
    para(doc, "", indent_chars=0, space_after=6)
    return t


def page_break(doc):
    doc.add_page_break()


def add_page_numbers(doc):
    """页脚居中页码。"""
    footer = doc.sections[0].footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    set_font(run, SONG, 10.5)
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    run._element.addnext(fld)


def setup(doc):
    st = doc.styles["Normal"]
    st.font.name = SONG
    st.font.size = Pt(12)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), SONG)
    for s in doc.sections:
        s.page_width = Cm(21.0)
        s.page_height = Cm(29.7)
        s.top_margin = Cm(2.54)
        s.bottom_margin = Cm(2.54)
        s.left_margin = Cm(3.17)
        s.right_margin = Cm(3.17)


